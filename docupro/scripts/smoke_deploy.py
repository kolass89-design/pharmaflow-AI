"""End-to-end smoke test for a deployed DOCUPRO instance.

Usage: python scripts/smoke_deploy.py https://docupro.example.com

Checks the public surface, then performs a real conversion with a generated
PDF and verifies the downloaded bytes. Exits non-zero on any failure, so it can
gate a deployment workflow.
"""

from __future__ import annotations

import json
import sys
import time
import urllib.error
import urllib.parse
import urllib.request

TIMEOUT = 30


def request(url: str, *, method: str = "GET", data: bytes | None = None, headers: dict | None = None):
    req = urllib.request.Request(url, data=data, method=method, headers=headers or {})
    with urllib.request.urlopen(req, timeout=TIMEOUT) as response:
        return response.status, dict(response.headers), response.read()


def build_pdf() -> bytes:
    import pymupdf

    doc = pymupdf.open()
    page = doc.new_page()
    page.insert_text((72, 100), "DOCUPRO deployment smoke test", fontsize=18)
    page.insert_text((72, 140), "This PDF was generated by scripts/smoke_deploy.py", fontsize=11)
    payload = doc.tobytes()
    doc.close()
    return payload


def multipart(fields: dict[str, str], files: list[tuple[str, str, bytes, str]]) -> tuple[bytes, str]:
    boundary = "----docupro" + str(int(time.time() * 1000))
    chunks: list[bytes] = []
    for name, value in fields.items():
        chunks.append(
            f'--{boundary}\r\nContent-Disposition: form-data; name="{name}"\r\n\r\n{value}\r\n'.encode()
        )
    for name, filename, content, content_type in files:
        chunks.append(
            (
                f'--{boundary}\r\nContent-Disposition: form-data; name="{name}"; filename="{filename}"\r\n'
                f"Content-Type: {content_type}\r\n\r\n"
            ).encode()
        )
        chunks.append(content)
        chunks.append(b"\r\n")
    chunks.append(f"--{boundary}--\r\n".encode())
    return b"".join(chunks), f"multipart/form-data; boundary={boundary}"


def main() -> int:
    if len(sys.argv) < 2:
        print(__doc__)
        return 2
    base = sys.argv[1].rstrip("/")
    report: dict[str, object] = {"baseUrl": base}
    failures: list[str] = []

    def check(name: str, condition: bool, detail: object = "") -> None:
        report[name] = {"ok": bool(condition), "detail": detail}
        if not condition:
            failures.append(name)
        print(f"{'PASS' if condition else 'FAIL'}  {name}  {detail}")

    try:
        status, headers, body = request(f"{base}/api/health")
        check("health", status == 200 and json.loads(body)["status"] == "ok", json.loads(body))
        check("security headers", headers.get("X-Content-Type-Options") == "nosniff")

        status, _, body = request(f"{base}/api/tools")
        catalog = json.loads(body)
        tools = catalog["tools"]
        available = [tool for tool in tools if tool["available"]]
        check("catalog", status == 200 and len(tools) >= 30, f"{len(available)}/{len(tools)} available")
        report["unavailable"] = [tool["id"] for tool in tools if not tool["available"]]

        status, _, body = request(f"{base}/api/capabilities")
        caps = json.loads(body)
        check("capabilities", status == 200 and "limits" in caps, caps.get("engines"))
        report["engines"] = caps.get("engines")

        status, _, body = request(f"{base}/")
        check("web client served", status == 200 and b"<div id=\"root\">" in body, len(body))

        pdf = build_pdf()
        form, content_type = multipart(
            {"tool": "pdf-to-word", "options": "{}"},
            [("files", "smoke.pdf", pdf, "application/pdf")],
        )
        status, _, body = request(
            f"{base}/api/jobs", method="POST", data=form, headers={"Content-Type": content_type}
        )
        job = json.loads(body)
        check("job accepted", status == 202 and "id" in job, job.get("id", "")[:8])

        state = {}
        deadline = time.time() + 180
        while time.time() < deadline:
            _, _, body = request(f"{base}/api/jobs/{job['id']}")
            state = json.loads(body)
            if state["status"] in {"succeeded", "failed", "cancelled"}:
                break
            time.sleep(1)
        check("job succeeded", state.get("status") == "succeeded", state.get("error"))
        if state.get("status") == "succeeded":
            artifact = state["artifacts"][0]
            check("artifact size", artifact["size"] > 1000, artifact["size"])
            url = urllib.parse.urljoin(base + "/", artifact["url"].lstrip("/"))
            status, headers, payload = request(url)
            check(
                "download",
                status == 200 and payload[:2] == b"PK" and len(payload) == artifact["size"],
                f"{len(payload)} bytes",
            )
            check("download is not cacheable", "no-store" in headers.get("Cache-Control", ""))
            bare = url.split("?")[0]
            try:
                request(bare)
                check("token required", False, "download succeeded without a token")
            except urllib.error.HTTPError as exc:
                check("token required", exc.code == 404, exc.code)

            started = time.time()
            request(f"{base}/api/jobs/{job['id']}", method="DELETE")
            while time.time() - started < 10:
                try:
                    _, _, body = request(f"{base}/api/jobs/{job['id']}")
                    state = json.loads(body)
                    if state["status"] == "expired":
                        break
                except urllib.error.HTTPError:
                    break
                time.sleep(0.5)
            check("delete on request", state.get("status") in {"expired", "deleted"}, state.get("status"))
    except Exception as exc:  # network failures must produce a readable report
        report["exception"] = f"{type(exc).__name__}: {exc}"
        failures.append("exception")

    print(json.dumps(report, indent=2)[:4000])
    print(f"\n{len(failures)} failure(s)" + (f": {', '.join(failures)}" if failures else ""))
    return 1 if failures else 0


if __name__ == "__main__":
    raise SystemExit(main())
